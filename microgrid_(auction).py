class WindTurbine(MicrogridComponent):
    """Represents a wind turbine."""
    def __init__(self, name, capacity):
        super().__init__(name)
        self.capacity = capacity  # Maximum power output in kW

    def update(self, timestep, data=None):
        """
        Update the wind turbine's power output based on wind speed data.

        Args:
            timestep: The current simulation timestep.
            data: A dictionary containing relevant data, e.g., {'wind_speed': float}.
        """
        if data and 'wind_speed' in data:
            wind_speed = data['wind_speed']
            # Simple wind power model (can be replaced with a more complex one)
            # Assuming a cut-in speed, rated speed, and cut-out speed
            cut_in_speed = 3  # m/s
            rated_speed = 12  # m/s
            cut_out_speed = 25  # m/s

            if wind_speed < cut_in_speed or wind_speed > cut_out_speed:
                self.power_output = 0
            elif wind_speed >= rated_speed:
                self.power_output = self.capacity
            else:
                # Linear interpolation between cut-in and rated speed
                self.power_output = self.capacity * (wind_speed - cut_in_speed) / (rated_speed - cut_in_speed)
        else:
            self.power_output = 0 # No wind data, no output

class PVSystem(MicrogridComponent):
    """Represents a PV (solar) system."""
    def __init__(self, name, capacity):
        super().__init__(name)
        self.capacity = capacity  # Maximum power output in kW

    def update(self, timestep, data=None):
        """
        Update the PV system's power output based on solar irradiance data.

        Args:
            timestep: The current simulation timestep.
            data: A dictionary containing relevant data, e.g., {'solar_irradiance': float}.
        """
        if data and 'solar_irradiance' in data:
            solar_irradiance = data['solar_irradiance'] # Assuming data is in W/m^2
            # Simple PV power model (can be replaced with a more complex one)
            # Assuming a standard test condition (STC) irradiance of 1000 W/m^2
            stc_irradiance = 1000
            self.power_output = self.capacity * (solar_irradiance / stc_irradiance)
            # Ensure output does not exceed capacity
            if self.power_output > self.capacity:
                self.power_output = self.capacity
            # Ensure output is not negative
            if self.power_output < 0:
                self.power_output = 0
        else:
            self.power_output = 0 # No solar data, no output

class DieselGenerator(MicrogridComponent):
    """Represents a diesel generator."""
    def __init__(self, name, capacity, fuel_consumption_rate=0.2, generation_cost_per_kwh=0.3): # Added generation_cost_per_kwh
        super().__init__(name)
        self.capacity = capacity  # Maximum power output in kW
        self.fuel_consumption_rate = fuel_consumption_rate # Example: fuel consumed per kWh generated
        self.generation_cost_per_kwh = generation_cost_per_kwh # Cost to generate 1 kWh
        self.fuel_level = 1000 # Example: initial fuel level
        self.is_running = False

    def update(self, timestep, data=None):
        """
        Update the diesel generator's power output and fuel level.

        Args:
            timestep: The current simulation timestep (in hours).
            data: A dictionary containing relevant data, e.g., {'required_power': float}.
                  This could also include commands to start/stop the generator.
        """
        required_power = data.get('required_power', 0) if data else 0

        # Ensure diesel only runs if fuel is available and required_power is positive
        if required_power > 0 and self.fuel_level > 0:
            self.is_running = True
            # Generate power up to capacity or required power, whichever is less
            power_to_generate = min(self.capacity, required_power)

            # Check if enough fuel to generate power_to_generate for the timestep
            max_power_from_fuel_kwh = (self.fuel_level / self.fuel_consumption_rate) if self.fuel_consumption_rate > 0 else float('inf')
            max_power_from_fuel_for_timestep = max_power_from_fuel_kwh / timestep if timestep > 0 else float('inf')

            self.power_output = min(power_to_generate, max_power_from_fuel_for_timestep)

            # Calculate fuel consumption based on actual generated power and rate
            fuel_consumed = self.power_output * self.fuel_consumption_rate * timestep
            self.fuel_level -= fuel_consumed
            if self.fuel_level < 0: # Should not happen if max_power_from_fuel is calculated correctly, but as a safeguard
                self.fuel_level = 0
                self.power_output = 0 # Cannot generate if fuel runs out mid-timestep

        else:
            self.is_running = False
            self.power_output = 0

    def get_fuel_level(self):
        """Get the current fuel level."""
        return self.fuel_level

    def __str__(self):
        return f"{self.name}: {self.power_output:.2f} kW, Fuel: {self.fuel_level:.2f}"

