import pandas as pd
import matplotlib.pyplot as plt

# Get the simulation history (assuming microgrid object is still defined)
history_data = microgrid.get_history()
history_df = pd.DataFrame(history_data)

# Retrieve component costs/prices from the microgrid object
diesel_gen = microgrid.components['diesel']
battery_comp = microgrid.components['battery']
grid_comp = microgrid.components['grid']

# Initialize cost/revenue columns
history_df['diesel_cost'] = 0.0
history_df['battery_cost'] = 0.0
history_df['grid_cost_revenue'] = 0.0

# Calculate costs/revenues for each timestep (assuming timestep=1 hour)
for i, row in history_df.iterrows():
    # Skip the initial state at time 0 (no power output/cost)
    if row['time'] == 0 and i == 0:
        continue

    # Diesel cost: Only when generating (power_output > 0)
    if row['diesel_power'] > 0:
        history_df.loc[i, 'diesel_cost'] = row['diesel_power'] * diesel_gen.generation_cost_per_kwh

    # Battery cost:
    # Discharge cost (power_output > 0 for discharge)
    if row['battery_power'] > 0:
        history_df.loc[i, 'battery_cost'] = row['battery_power'] * battery_comp.discharge_cost_per_kwh
    # Charge cost (power_output < 0 for charge)
    elif row['battery_power'] < 0:
        history_df.loc[i, 'battery_cost'] = abs(row['battery_power']) * battery_comp.charge_cost_per_kwh

    # Grid cost/revenue:
    # Import cost (power_output > 0 for import)
    if row['grid_power'] > 0:
        history_df.loc[i, 'grid_cost_revenue'] = row['grid_power'] * grid_comp.import_price_per_kwh
    # Export revenue (power_output < 0 for export, so revenue is negative cost)
    elif row['grid_power'] < 0:
        history_df.loc[i, 'grid_cost_revenue'] = row['grid_power'] * grid_comp.export_price_per_kwh # power_output is negative, export_price is positive, result is negative (revenue)

# Calculate total operational cost (sum of all costs/revenues)
history_df['total_operational_cost'] = history_df['diesel_cost'] + history_df['battery_cost'] + history_df['grid_cost_revenue']

# Set display option to show full float precision
pd.set_option('display.float_format', '{:.3f}'.format)

