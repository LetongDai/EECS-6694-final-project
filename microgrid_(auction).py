class Microgrid:
    """Represents the microgrid simulation environment."""
    def __init__(self, components):
        """
        Args:
            components: A dictionary of MicrogridComponent objects, e.g., {'wind': WindTurbine(...), 'battery': Battery(...), ...}.
        """
        self.components = components
        self.time = 0
        self.history = [] # To store simulation results

    def update(self, timestep, data):
        """
        Update the state of all components for the current timestep and manage power balance using economic dispatch.

        Args:
            timestep: The duration of the current timestep (in hours).
            data: A dictionary containing data for each component, e.g., {'wind': {'wind_speed': ...}, 'customer_load': {'load': ...}}.
        """
        current_state = {'time': self.time}
        total_generation_renewables = 0
        total_load_consumption = 0

        # Reset power_output for dispatchable components before new dispatch calculations
        # Renewables and load update first, their output directly determined by data
        for name, component in self.components.items():
            if name in ['diesel', 'battery', 'grid']:
                component.power_output = 0 # Clear previous dispatch output

        # Update renewable sources and load first
        for name, component in self.components.items():
            component_data = data.get(name, {})
            if name in ['wind', 'pv']: # Renewable sources
                 component.update(timestep, component_data)
                 current_state[name + '_power'] = component.get_power_output()
                 total_generation_renewables += component.get_power_output()
            elif name == 'load': # Load
                 component.update(timestep, component_data)
                 current_state[name + '_power'] = component.get_power_output()
                 total_load_consumption += component.get_power_output() # load_power is negative, so adding it increases the deficit

        net_power_balance_after_renewables_load = total_generation_renewables + total_load_consumption
        power_to_balance = -net_power_balance_after_renewables_load # Positive means deficit, negative means surplus

        # Components involved in balancing
        diesel = self.components.get('diesel')
        battery = self.components.get('battery')
        grid = self.components.get('grid')

        # --- Economic Dispatch / Simplified Auction Logic ---
        if power_to_balance > 0:  # Deficit - Need to supply power
            suppliers = []
            if diesel:
                max_diesel_power_available_kwh = (diesel.get_fuel_level() / diesel.fuel_consumption_rate) if diesel.fuel_consumption_rate > 0 else float('inf')
                max_diesel_power_available = min(diesel.capacity, max_diesel_power_available_kwh / timestep if timestep > 0 else float('inf'))
                if max_diesel_power_available > 0:
                    suppliers.append({'name': 'diesel', 'component': diesel, 'cost': diesel.generation_cost_per_kwh, 'max_supply': max_diesel_power_available})
            if battery:
                max_battery_discharge_power_kwh = battery.get_soc() * battery.capacity_kwh
                max_battery_discharge_power = min(battery.max_discharge_rate_kw, max_battery_discharge_power_kwh / timestep if timestep > 0 else float('inf'))
                if max_battery_discharge_power > 0:
                    suppliers.append({'name': 'battery_discharge', 'component': battery, 'cost': battery.discharge_cost_per_kwh, 'max_supply': max_battery_discharge_power})
            if grid:
                max_grid_import_power = grid.import_limit
                if max_grid_import_power > 0:
                    suppliers.append({'name': 'grid_import', 'component': grid, 'cost': grid.import_price_per_kwh, 'max_supply': max_grid_import_power})

            # Sort suppliers by cost (cheapest first)
            suppliers.sort(key=lambda x: x['cost'])

            for supplier in suppliers:
                if power_to_balance <= 0:
                    break

                # Determine how much power this supplier should try to provide
                power_to_provide_by_supplier = min(power_to_balance, supplier['max_supply'])

                # Update the component and get its actual power output
                if supplier['name'] == 'diesel':
                    supplier['component'].update(timestep, {'required_power': power_to_provide_by_supplier})
                elif supplier['name'] == 'battery_discharge':
                    supplier['component'].update(timestep, {'discharge_power': power_to_provide_by_supplier})
                elif supplier['name'] == 'grid_import':
                    supplier['component'].update(timestep, {'requested_power': power_to_provide_by_supplier}) # Positive for import

                actual_power_supplied = supplier['component'].get_power_output() # This is positive for supply
                power_to_balance -= actual_power_supplied

                # Store the updated power for this component
                if supplier['name'] == 'diesel':
                    current_state['diesel_power'] = actual_power_supplied
                elif supplier['name'] == 'battery_discharge':
                    current_state['battery_power'] = actual_power_supplied
                elif supplier['name'] == 'grid_import':
                    current_state['grid_power'] = actual_power_supplied

        elif power_to_balance < 0:  # Surplus - Need to absorb power
            consumers = []
            power_to_absorb = -power_to_balance # Convert to positive quantity for absorption

            if battery:
                max_battery_charge_power_kwh = (1.0 - battery.get_soc()) * battery.capacity_kwh
                max_battery_charge_power = min(battery.max_charge_rate_kw, max_battery_charge_power_kwh / timestep if timestep > 0 else float('inf'))
                if max_battery_charge_power > 0:
                    consumers.append({'name': 'battery_charge', 'component': battery, 'cost': battery.charge_cost_per_kwh, 'max_consume': max_battery_charge_power})
            if grid:
                max_grid_export_power = grid.export_limit
                if max_grid_export_power > 0:
                    # Exporting yields revenue, so its 'cost' for absorbing surplus is negative (profit)
                    consumers.append({'name': 'grid_export', 'component': grid, 'cost': -grid.export_price_per_kwh, 'max_consume': max_grid_export_power})

            # Sort consumers by cost (most "profitable" or least expensive to absorb first, i.e., lowest cost value)
            consumers.sort(key=lambda x: x['cost'])

            for consumer in consumers:
                if power_to_absorb <= 0:
                    break

                # Determine how much power this consumer should try to absorb
                power_to_send_to_consumer = min(power_to_absorb, consumer['max_consume'])

                # Update the component
                if consumer['name'] == 'battery_charge':
                    consumer['component'].update(timestep, {'charge_power': power_to_send_to_consumer})
                elif consumer['name'] == 'grid_export':
                    consumer['component'].update(timestep, {'requested_power': -power_to_send_to_consumer}) # Negative for export

                actual_power_absorbed = -consumer['component'].get_power_output() # get_power_output is negative for charge/export, so make it positive for absorption
                power_to_absorb -= actual_power_absorbed

                # Store the updated power for this component
                if consumer['name'] == 'battery_charge':
                    current_state['battery_power'] = consumer['component'].get_power_output()
                elif consumer['name'] == 'grid_export':
                    current_state['grid_power'] = consumer['component'].get_power_output()

            power_to_balance = -power_to_absorb # Convert back to original sign convention (remaining surplus is negative)

        # Ensure all components (including those not involved in dispatch decisions) have their power_output recorded
        for name, component in self.components.items():
            if name + '_power' not in current_state:
                 current_state[name + '_power'] = component.get_power_output()

        # Store battery SOC
        if battery:
            current_state['battery_soc'] = battery.get_soc()

        # The final net_power_balance reflects any remaining imbalance after dispatch
        current_state['net_power_balance'] = power_to_balance

        # Store the current state
        self.history.append(current_state)

        # Advance time
        self.time += timestep

    def run_simulation(self, timesteps, data_series):
        """
        Run the microgrid simulation for a specified number of timesteps.

        Args:
            timesteps: The total number of timesteps to simulate.
            data_series: A list of dictionaries, where each dictionary contains the data for a single timestep.
                         The length of this list should be equal to the number of timesteps.
        """
        self.history = [] # Reset history for a new simulation run
        self.time = 0 # Reset time

        # Initialize component states at time 0 before the first update
        initial_state = {'time': self.time}
        for name, component in self.components.items():
             initial_state[name + '_power'] = component.get_power_output() # Should be 0 initially for most
        initial_state['net_power_balance'] = 0 # Assuming initial state is balanced
        # Initialize battery SOC for time 0
        if 'battery' in self.components:
            initial_state['battery_soc'] = self.components['battery'].get_soc()
        self.history.append(initial_state)


        for i in range(timesteps):
            timestep_data = data_series[i]
            # Assuming each step represents 1 hour for now
            self.update(1, timestep_data)
            # print(f"Time: {self.time}h, Net Balance (after dispatch): {self.history[-1]['net_power_balance']:.2f} kW") # Commented out to reduce output

    def get_history(self):
        """Get the simulation history."""
        return self.history

    def __str__(self):
        return f"Microgrid with components: {', '.join(self.components.keys())}"

